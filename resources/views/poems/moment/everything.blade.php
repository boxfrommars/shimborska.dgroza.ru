        <h3>Wszystko</h3>

        <p>
            Wszystko&nbsp;–<br/>
            słowo bezczelne i nadęte pychą.<br/>
            Powinno być pisane w cudzysłowie.<br/>
            Udaje, że niczego nie pomija,<br/>
            że skupia, obejmuje, zawiera i ma.<br/>
            A tymczasem jest tylko<br/>
            strzępkiem zawieruchy.
        </p>
