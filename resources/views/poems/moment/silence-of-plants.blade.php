        <h3>Milczenie roślin</h3>

        <p>
            Jednostronna znajomość między mną a wami<br/>
            rozwija się nie najgorzej.
        </p>
        <p>
            Wiem co listek, co płatek, kłos, szyszka, łodyga,<br/>
            i co się z wami dzieje w kwietniu, a co w grudniu.
        </p>
        <p>
            Chociaż moja ciekawość jest bez wzajemności,<br/>
            nad niektórymi schylam się specjalnie,<br/>
            a ku niektórym z was zadzieram głowę.
        </p>
        <p>
            Macie u mnie imiona:<br/>
            klon, łopian, przylaszczka,<br/>
            wrzos, jałowiec, jemioła, niezapominajka,<br/>
            a ja u was żadnego.
        </p>
        <p>
            Podróż nasza jest wspólna.<br/>
            W czasie wspólnych podróży rozmawia się przecież,<br/>
            wymienia się uwagi choćby o pogodzie,<br/>
            albo o stacjach mijanych w rozpędzie.
        </p>
        <p>
            Nie brakłoby tematów, bo łączy nas wiele.<br/>
            Ta sama gwiazda trzyma nas w zasięgu.<br/>
            Rzucamy cienie na tych samych prawach.
        </p>
        <p>
            Próbujemy coś wiedzieć, każde na swój sposób,<br/>
            a to, czego nie wiemy, to też podobieństwo.
        </p>
        <p>
            Objaśnię jak potrafię, tylko zapytajcie:<br/>
            co to takiego oglądać oczami,<br/>
            po co serce mi bije<br/>
            i czemu moje ciało nie zakorzenione.
        </p>
        <p>
            Ale jak odpowiadać na niestawiane pytania,<br/>
            jeśli w dodatku jest się kimś<br/>
            tak bardzo dla was nikim.
        </p>
        <p>
            Porośla, zagajniki, łąki i szuwary —<br/>
            wszystko, co do was mówię, to monolog,<br/>
            i nie wy go słuchacie.
        </p>
        <p>
            Rozmowa z wami konieczna jest i niemożliwa.<br/>
            Pilna w życiu pośpiesznym<br/>
            i odłożona na nigdy.
        </p>
    </div>
