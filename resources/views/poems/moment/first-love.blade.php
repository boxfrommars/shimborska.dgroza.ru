    <h2>Первая любовь</h2>

    <div class="poem">
        <p>
            Говорят,<br/>
            первая любовь — самая-самая.<br/>
            Весьма романтично,<br/>
            но со мной всё не так.
        </p>
        <p>
            Что-то между нами было и не было,<br/>
            творилось и затворилось.
        </p>
        <p>
            У меня не дрожат руки,<br/>
            когда натыкаюсь на разные вещицы<br/>
            и письма, перевязанные веревочкой —<br/>
            нет чтобы лентой.
        </p>
        <p>
            Единственная наша встреча спустя годы —<br/>
            разговор двух стульев<br/>
            у холодного столика.
        </p>
        <p>
            Другие любови<br/>
            всё еще глубоко дышат во мне.<br/>
            А у этой нет вдоха даже для вздоха.
        </p>
        <p>
            И всё же, какая-никакая,<br/>
            она умеет то, что другим не под силу:
        </p>
        <p>
            позабытая,<br/>
            даже не снящаяся,<br/>
            приучает меня к смерти.
        </p>
        <p class="foot-note">
            Перевод Асара Эппеля
        </p>
    </div>

    <div class="poem" lang="pl">
        <h3>Pierwsza miłość</h3>

        <p>
            Mówią,<br/>
            że pierwsza miłość najważniejsza.<br/>
            To bardzo romantyczny<br/>
            ale nie mój przypadek.
        </p>
        <p>
            Coś między nami było i nie było<br/>
            działo się i podziało.
        </p>
        <p>
            Nie drżą mi ręce,<br/>
            kiedy natrafiam na drobne pamiątki<br/>
            i zwitek listów przewiązanych sznurkiem<br/>
            — żeby chociaż wstążeczką.
        </p>
        <p>
            Nasze jedyne spotkanie po latach<br/>
            to rozmowa dwóch krzeseł<br/>
            przy zimnym stoliku.
        </p>
        <p>
            Inne miłości<br/>
            głęboko do tej pory oddychają we mnie.<br/>
            Tej brak tchu, żeby westchnąć.
        </p>
        <p>
            A jednak właśnie taka, jaka jest,<br/>
            potrafi, czego tamte nie potrafią jeszcze:
        </p>
        <p>
            niepamiętana,<br/>
            nie śniąca się nawet<br/>
            oswaja mnie ze śmiercią.
        </p>
    </div>
