            gdzie prócz wejściówki<br/>
            obowiązuje wyjściówka;
        </p>
        <p>
            Co z całym światem żywym,<br/>
            którego nie zdążę<br/>
            z innym żywym porównać;
        </p>
        <p>
            O czym będą pisały<br/>
            nazajutrz gazety;
        </p>
        <p>
            Kiedy ustaną wojny<br/>
