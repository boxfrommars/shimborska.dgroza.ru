            bo albo za wcześnie na nie,<br/>
            albo nie zdołam ich pojąć.
        </p>
        <p>
            Spis pytań jest długi,<br/>
            porusza sprawy ważne i mniej ważne,<br/>
            a że nie chcę was nudzić,<br/>
            wyjawię tylko niektóre:
        </p>
        <p>
            Co było rzeczywiste,<br/>
            a co się ledwie zdawało<br/>
            na tej widowni<br/>
