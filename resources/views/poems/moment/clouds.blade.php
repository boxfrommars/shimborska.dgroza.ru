    <div class="poem" lang="pl">
        <h3>Chmury</h3>

        <p>
            Z opisywaniem chmur<br/>
            musiałabym się bardzo śpieszyć —<br/>
            już po ułamku chwili<br/>
            przestają być te, zaczynają być inne.
        </p>
        <p>
            Ich właściwością jest<br/>
            nie powtarzać się nigdy<br/>
            w kształtach, odcieniach, pozach i układzie.
        </p>
        <p>
            Nie obciążone pamięcią o niczym,<br/>
            unoszą się bez trudu nad faktami.
        </p>
        <p>
            Jacy tam z nich świadkowie czegokolwiek —<br/>
            natychmiast rozwiewają się na wszystkie strony.
        </p>
        <p>
            W porównaniu z chmurami<br/>
            życie wydaje się ugruntowane,<br/>
            omal że trwałe i prawie że wieczne.
        </p>
        <p>
            Przy chmurach<br/>
            nawet kamień wygląda jak brat,<br/>
            na którym można polegać,<br/>
            a one, cóż, dalekie i płoche kuzynki.
        </p>
        <p>
            Niech sobie ludzie będą, jeśli chcą,<br/>
            a potem po kolei każde z nich umiera,<br/>
            im, chmurom nic do tego<br/>
            wszystkiego<br/>
            bardzo dziwnego.
        </p>
        <p>
            Nad całym Twoim życiem<br/>
            i moim, jeszcze nie całym,<br/>
            paradują w przepychu jak paradowały.
        </p>
        <p>
            Nie mają obowiązku razem z nami ginąć.<br/>
            Nie muszą być widziane, żeby płynąć.
        </p>
    </div>
