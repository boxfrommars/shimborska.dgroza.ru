            упроченной, чуть ли даже не вечной,
        </p>
        <p>
            камень и тот<br/>
            все равно что брат,<br/>
            на которого можно положиться,<br/>
            они же — далекие ветреные и двоюродные.
        </p>
        <p>
            Пусть люди себе побудут, если охота,<br/>
