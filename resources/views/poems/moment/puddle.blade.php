    <div class="poem">
        <h3>Kałuża</h3>

        <p>
            Dobrze z dzieciństwa pamiętam ten lęk.<br/>
            Omijałam kałuże,<br/>
            zwłaszcza te świeże, po deszczu.<br/>
            Któraś z nich przecież mogła nie mieć dna,<br/>
            choć wyglądała jak inne.
        </p>
        <p>
            Stąpnę i nagle zapadnę się cała,<br/>
            zacznę wzlatywać w dół<br/>
            i jeszcze głębiej w dół,<br/>
            w kierunku chmur odbitych<br/>
            a może i dalej.
        </p>
        <p>
            Potem kałuża wyschnie,<br/>
            zamknie się nade mną,<br/>
            a ja na zawsze zatrzaśnięta — gdzie —<br/>
            z niedoniesionym na powierzchnię krzykiem.
        </p>
        <p>
            Dopiero później przyszło zrozumienie:<br/>
            nie wszystkie złe przygody<br/>
            mieszczą się w regułach świata<br/>
            i nawet gdyby chciały,<br/>
            nie mogą się zdarzyć.
        </p>
    </div>
