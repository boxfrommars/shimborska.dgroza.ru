            особенно недавние, после дождя.<br/>
            Какая-то могла оказаться бездонной,<br/>
            хоть по виду не отличалась от остальных.
        </p>
        <p>
            Наступлю вдруг и целиком сорвусь,<br/>
            начну взлетать вниз,<br/>
            глубже и глубже,<br/>
            туда к отразившимся тучам<br/>
            и еще дальше.
        </p>
        <p>
            Потом лужа высохнет,<br/>
            сомкнется надо мной,<br/>
            а я навсегда канувшая — куда? —<br/>
            с не долетающим наружу криком.
        </p>
        <p>
            И только позже я поняла:<br/>
            не все недобрые приключения<br/>
            включены в правила мира<br/>
            и, даже если бы захотели,<br/>
            не могут произойти.
        </p>
        <p class="foot-note">
            Перевод Асара Эппеля
        </p>
