        </p>
        <p>
            Каждый пока еще цельность<br/>
            со своим лицом<br/>
            и надежно скрытого кровью.
        </p>
        <p>
            Еще довольно времени,<br/>
            чтоб разметало волосы,<br/>
            а из кармана вывалились<br/>
