    <div class="poem" lang="pl">
        <h3>Fotografia z 11 września</h3>

        <p>
            Skoczyli z płonących pięter w dół —<br/>
            jeden, dwóch, jeszcze kilku<br/>
            wyżej, niżej.
        </p>
        <p>
            Fotografia powstrzymała ich przy życiu,<br/>
            a teraz przechowuje<br/>
            nad ziemią ku ziemi.
        </p>
        <p>
            Każdy to jeszcze całość<br/>
            z osobistą twarzą<br/>
            i krwią dobrze ukrytą.
        </p>
        <p>
            Jest dosyć czasu,<br/>
            żeby rozwiały się włosy,<br/>
            a z kieszeni wypadły<br/>
            klucze, drobne pieniądze.
        </p>
        <p>
            Są ciągle jeszcze w zasięgu powietrza,<br/>
            w obrębie miejsc,<br/>
            które się właśnie otwarły.
        </p>
        <p>
            Tylko dwie rzeczy mogę dla nich zrobić —<br/>
            opisać ten lot<br/>
            i nie dodawać ostatniego zdania.
        </p>
    </div>

    <div class="poem">
        <h3>Сфотографированное 11 сентября</h3>

        <p>
