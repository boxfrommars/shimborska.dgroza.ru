        </p>
        <p>
            Они пока что в пределах воздуха,<br/>
            в его отрезках,<br/>
            которые мгновение как отворились.
        </p>
        <p>
            Всего-то две вещи я могу для них сделать —<br/>
            описать полет<br/>
            и не ставить последней фразы.
        </p>
        <p class="foot-note">Перевод Асара Эппеля</p>
