            Łyżeczkę gorzkiej wiedzy o smaku lekarstwa.
        </p>
        <p>
            Drobne nieposłuszeństwa,<br/>
            w tym któreś śmiertelne.<br/>
            Wesołą pogoń za piłką po szosie.<br/>
            Szczęście ślizgania się po kruchym lodzie.
        </p>
        <p>
            Ten tam i tamta obok i ci z brzegu:<br/>
            zanim zdążyli dorosnąć do klamki,<br/>
            zepsuć zegarek,<br/>
            rozbić pierwszą szybę.
        </p>
        <p>
            Małgorzatka, lat cztery,<br/>
            z czego dwa na leżąco i patrząco w sufit.
        </p>
        <p>
