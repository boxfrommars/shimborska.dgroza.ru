        <h3>Ze wspomnień</h3>

        <p>
            Gawędziliśmy sobie,<br/>
            zamilkliśmy nagle.<br/>
            Na taras weszła dziewczyna,<br/>
            ach, piękna,<br/>
            zanadto piękna<br/>
            jak na nasz spokojny tutaj pobyt.
        </p>
        <p>
            Basia zerknęła w popłochu na męża.<br/>
            Krystyna odruchowo położyła dłoń<br/>
            na dłoni Zbyszka.<br/>
            Ja pomyślałam: zadzwonię do ciebie,<br/>
            jeszcze na razie&nbsp;– powiem&nbsp;– nie przyjeżdżaj,<br/>
            zapowiadają właśnie kilkudniowe deszcze.
        </p>
        <p>
            Tylko Agnieszka, wdowa,<br/>
            powitała piękną uśmiechem.
        </p>
