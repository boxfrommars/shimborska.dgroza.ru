        <h3>Tarsjusz</h3>
        <p>
            Ja tarsjusz syn tarsjusza,<br/>
            wnuk tarsjusza i prawnuk,<br/>
            zwierzątko małe, złożone z dwóch źrenic<br/>
            i tylko bardzo już koniecznej reszty;<br/>
            cudownie ocalony od dalszej przeróbki,<br/>
            bo przysmak ze mnie żaden,<br/>
            na kołnierz są więksi,<br/>
            gruczoły moje nie przynoszą szczęścia,<br/>
            koncerty odbywają się bez moich jelit;<br/>
            ja tarsjusz<br/>
            siedzę żywy na palcu człowieka.
        </p>
        <p>
            Dzień dobry, wielki panie,<br/>
            co mi za to dasz,<br/>
            że mi niczego nie musisz odbierać?<br/>
            Swoją wspaniałomyślność czym mi wynagrodzisz?<br/>
            Jaką mi, bezcennemu, przyznasz cenę<br/>
            za pozowanie do twoich uśmiechów?<br/>
            Wielki pan dobry&nbsp;–<br/>
            wielki pan łaskawy&nbsp;–<br/>
            któż by mógł o tym świadczyć, gdyby brakło<br/>
            zwierząt niewartych śmierci?<br/>
            Wy sami może?
        </p>
        <p>
            Ależ to, co już o sobie wiecie,<br/>
