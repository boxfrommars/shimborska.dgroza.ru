    <div class="poem" lang="pl">
        <h3>Wietnam</h3>
        <p>
            Kobieto, jak się nazywasz?&nbsp;– Nie wiem.<br/>
            Kiedy się urodziłaś, skąd pochodzisz?&nbsp;– Nie wiem.<br/>
            Dlaczego wykopałaś sobie norę w ziemi?&nbsp;– Nie wiem.<br/>
            Odkąd się tu ukrywasz?&nbsp;– Nie wiem.<br/>
            Czemu ugryzłaś mnie w serdeczny palec?&nbsp;– Nie wiem.<br/>
            Czy wiesz, że nie zrobimy ci nic złego?&nbsp;– Nie wiem.<br/>
            Po czyjej jesteś stronie?&nbsp;– Nie wiem.<br/>
            Teraz jest wojna, musisz wybrać.&nbsp;– Nie wiem.<br/>
            Czy twoja wieś jeszcze istnieje?&nbsp;– Nie wiem.<br/>
            Czy to są twoje dzieci?&nbsp;– Tak.
        </p>
