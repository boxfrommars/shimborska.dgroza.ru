            spotkać się po latach.
        </p>
        <p>
            Nasze tygrysy piją mleko.<br/>
            Nasze jastrzębie chodzą pieszo.<br/>
            Nasze rekiny toną w wodzie.<br/>
            Nasze wilki ziewają przed otwartą klatką.
        </p>
        <p>
            Nasze żmije otrząsnęły się z błyskawic,<br/>
