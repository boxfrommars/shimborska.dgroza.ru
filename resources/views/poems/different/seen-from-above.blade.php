    <div class="poem" lang="pl">
        <h3>Widziane z góry</h3>
        <p>
            Na polnej drodze leży martwy żuk.<br/>
            Trzy pary nóżek złożył na brzuchu starannie.<br/>
            Zamiast bezładu śmierci — schludność i porządek.<br/>
            Groza tego widoku jest umiarkowana,<br/>
            zakres ściśle lokalny od perzu do mięty.<br/>
            Smutek się nie udziela.<br/>
            Niebo jest błękitne.
        </p>
        <p>
            Dla naszego spokoju, śmiercią jakby płytszą<br/>
            nie umierają, ale zdychają zwierzęta<br/>
            tracąc — chcemy w to wierzyć — mniej czucia i świata,<br/>
            schodząc — jak nam się zdaje — z mniej tragicznej sceny.<br/>
            Ich potulne duszyczki nie straszą nas nocą,<br/>
            szanują dystans,<br/>
            wiedzą, co to mores.
        </p>
        <p>
            I oto ten na drodze martwy żuk<br/>
            w nieopłakanym stanie ku słonku polśniewa.
        </p>
        <p>
            Wystarczy o nim tyle pomyśleć, co spojrzeć:<br/>
            wygląda, że nie stało mu się nic ważnego.<br/>
            Ważne związane jest podobno z nami.<br/>
            Na życie tylko nasze, naszą tylko śmierć,<br/>
            śmierć, która wymuszonym cieszy się pierwszeństwem.
        </p>
    </div>
