        <h3>Pogoń</h3>
        <p>
            Wiem, że powita mnie cisza, a jednak.<br/>
            Nie wrzawa, nie fanfary, nie poklask, a jednak.<br/>
            Ani dzwony na trwogę, ani sama trwoga.
        </p>
        <p>
            Nie liczę nawet na listeczek suchy,<br/>
