            mądrości w kulach z kryształu, a jednak.
        </p>
        <p>
            Rozumiem, że nie po to chodzę po Księżycu,<br/>
            żeby szukać pierścionków, pogubionych wstążek.<br/>
            Oni wszystko zawczasu zabierają z sobą.
        </p>
        <p>
            Niczego, co by mogło świadczyć, że.<br/>
            Śmieci, gratów, obierków, szpargałów, okruszyn,<br/>
            odłamków, wiórków, stłuczków, ochłapów, rupieci.
        </p>
        <p>
            Ja, naturalnie, schylam się tylko po kamyk,<br/>
            z którego nie odczytam, dokąd się udali.<br/>
            Nie lubią mi zostawiać znaku.<br/>
            Są niezrównani w sztuce zacierania śladów.
        </p>
        <p>
            Od wieków znam ich talent do znikania w porę,<br/>
            ich boską nieuchwytność za rogi, za ogon,<br/>
            za rąbek szatki rozdętej w odlocie.<br/>
            Nigdy im włos nie spadnie z głowy, abym miał.
        </p>
        <p>
            Wszędzie o myśl chytrzejsi niż ja sam,<br/>
            zawsze o krok przede mną, nim dobiegnąć zdążę,<br/>
            wystawiany szyderczo na trudy pierwszeństwa.
        </p>
        <p>
            Nie ma ich, nigdy nie było, a jednak<br/>
            muszę to sobie raz po raz powtarzać,<br/>
            starać się nie być dzieckiem, któremu się zdaje.
        </p>
        <p>
