            Ciało bez przymiarki.<br/>
            Głowa bez namysłu.
        </p>
        <p>
            Nie znam roli, którą gram.<br/>
            Wiem tylko, że jest moja, niewymienna.
        </p>
        <p>
            O czym jest sztuka,<br/>
            zgadywać muszę wprost na scenie.
        </p>
        <p>
            Kiepsko przygotowana do zaszczytu życia,<br/>
            narzucone mi tempo akcji znoszę z trudem.<br/>
            Improwizuję, choć brzydzę się improwizacją.<br/>
            Potykam się co krok o nieznajomość rzeczy.<br/>
            Mój sposób bycia zatrąca zaściankiem.<br/>
            Moje instynkty to amatorszczyzna.<br/>
            Trema, tłumacząc mnie, tym bardziej upokarza.<br/>
            Okoliczności łagodzące odczuwam jako okrutne.
        </p>
        <p>
            Nie do cofnięcia słowa i odruchy,<br/>
            nie doliczone gwiazdy,<br/>
            charakter jak płaszcz w biegu dopinany —<br/>
            oto żałosne skutki tej nagłości.
        </p>
        <p>
            Gdyby choć jedną środę przećwiczyć zawczasu,<br/>
            albo choć jeden czwartek raz jeszcze powtórzyć!<br/>
            A tu już piątek nadchodzi z nie znanym mi scenariuszem.<br/>
            Czy to w porządku — pytam<br/>
            (z chrypką w głosie,<br/>
            bo nawet mi nie dano odchrząknąć za kulisami).
        </p>
        <p>
            Złudna jest myśl, że to tylko pobieżny egzamin<br/>
