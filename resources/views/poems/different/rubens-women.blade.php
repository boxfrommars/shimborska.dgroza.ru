    <div class="poem" lang="pl">
        <h3>Kobiety Rubensa</h3>
        <p>
            Waligórzanki, żeńska fauna<br/>
            jak łoskot beczek nagie.<br/>
            Gnieżdżą się w stratowanych łożach,<br/>
            śpią z otwartymi do piania ustami.<br/>
            Źrenice ich uciekły w głąb<br/>
            i penetrują do wnętrza gruczołów,<br/>
            z których się drożdże sączą w krew.
        </p>
        <p>
            Córy baroku. Tyje ciasto w dzieży,<br/>
            parują łaźnie, rumienią się wina,<br/>
            cwałują niebem prosięta obłoków,<br/>
            rżą trąby na fizyczny alarm.
        </p>
        <p>
            O rozdynione, o nadmierne<br/>
            i podwojone odrzuceniem szaty,<br/>
            i potrojone gwałtownością pozy<br/>
            tłuste dania miłosne!
        </p>
        <p>
            Ich chude siostry wstały wcześniej,<br/>
            zanim się rozwidniło na obrazie.<br/>
            I nikt nie widział, jak gęsiego szły<br/>
            po niezamalowanej stronie płótna.
        </p>
        <p>
            Wygnanki stylu. Żebra przeliczone,<br/>
            ptasia natura stóp i dłoni.<br/>
            Na sterczących łopatkach próbują ulecieć.
        </p>
        <p>
            Trzynasty wiek dałby im złote tło.<br/>
            Dwudziesty — dałby ekran srebrny.<br/>
            Ten siedemnasty nic dla płaskich nie ma.
        </p>
        <p>
            Albowiem nawet niebo jest wypukłe,<br/>
            wypukli aniołowie i wypukły bóg —<br/>
            Febus wąsaty, który na spoconym<br/>
            rumaku wjeżdża do wrzącej alkowy.
        </p>
