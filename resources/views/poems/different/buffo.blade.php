    <div class="poem" lang="pl">
        <h3>Buffo</h3>
        <p>
            Najpierw minie nasza miłość,<br/>
            potem sto i dwieście lat,<br/>
            potem znów będziemy razem:<br/>
        </p>
        <p>
            komediantka i komediant,<br/>
            ulubieńcy publiczności,<br/>
            odegrają nas w teatrze.<br/>
            Mała farsa z kupletami,<br/>
            trochę tańca, dużo śmiechu,<br/>
            trafny rys obyczajowy<br/>
            i oklaski.
        </p>
        <p>
            Będziesz śmieszny nieodparcie<br/>
            na tej scenie, z tą zazdrością,<br/>
            w tym krawacie.
        </p>
        <p>
            Moja głowa zawrócona,<br/>
            moje serce i korona,<br/>
            głupie serce pękające<br/>
            i korona spadająca.
        </p>
        <p>
            Będziemy się spotykali,<br/>
            rozstawali, śmiech na sali,<br/>
            siedem rzek, siedem gór<br/>
            między sobą obmyślali.<br/>
            I jakby nam było mało<br/>
            rzeczywistych klęsk i cierpień<br/>
            — dobijemy się słowami.
        </p>
        <p>
            A potem się pokłonimy<br/>
            i to będzie farsy kres.<br/>
            Spektatorzy pójdą spać<br/>
            ubawiwszy się do łez.
        </p>
        <p>
            Oni będą ślicznie żyli,<br/>
            oni miłość obłaskawią,<br/>
            tygrys będzie jadł z ich ręki.
        </p>
        <p>
            A my wiecznie jacyś tacy,<br/>
            a my w czapkach z dzwoneczkami,<br/>
            w ich dzwonienie barbarzyńsko<br/>
            zasłuchani.
        </p>
    </div>
