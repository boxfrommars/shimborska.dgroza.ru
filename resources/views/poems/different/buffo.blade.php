            Поначалу минут страсти,<br/>
            после — сто и двести лет,<br/>
            после снова будем вместе:
        </p>
        <p>
            лицедей и лицедейка —<br/>
            театральные любимцы<br/>
            нас изобразят на сцене.
        </p>
        <p>
            Ходкий фарс, куплетик ловкий,<br/>
            бойкий танец, много смеха,<br/>
            точный штрих по части быта,<br/>
            крики «браво».
        </p>
        <p>
            Будешь ты смешон ужасно<br/>
            в этом галстуке, ревнивый,<br/>
            на подмостках.
        </p>
        <p>
            Я — в короне, и кружится<br/>
            голова, и сердце тщится;<br/>
            глупое, оно забылось,<br/>
            и корона покатилась.
        </p>
        <p>
            Мы начнем с тобой встречаться,<br/>
            расставаться, зал — смеяться,<br/>
            семь препон, семь преград —<br/>
            между тем нагромоздятся.<br/>
            И как будто с нас не станет<br/>
            настоящих мук и горя —<br/>
            мы добьем себя словами.
        </p>
        <p>
            А потом поклон со сцены<br/>
            кончен фарс обид и поз.<br/>
            Зрители уходят спать,<br/>
            позабавившись до слез.
        </p>
        <p>
            Будут жить они прекрасно,<br/>
            ублажить любовь сумеют,<br/>
            тигра выкормят с ладони.
        </p>
        <p>
            Мы ж — какие-то такие,<br/>
            в колпаках и с бубенцами,<br/>
            одурманенные напрочь<br/>
            их бренчаньем.
        </p>
