        </p>
        <p>
            Я высновидела им стол, два стула. Сели.<br/>
            Опять родные и опять живые.<br/>
            Светильни лиц их в сумерках блеснули<br/>
            мне, словно Рембрандту.
        </p>
        <p>
            Теперь могу решиться рассказать,<br/>
            по скольким снам они скитались, в скольких толпах<br/>
            вытаскивала их из-под колес,<br/>
            в скольких агониях со скольких срывались моих рук.<br/>
            Отрезанные — отрастали криво.<br/>
            Нелепость вынуждала их рядиться.<br/>
            Пусть вне меня их не снедало это —<br/>
            что из того? — когда во мне снедало.<br/>
            Приснившаяся чернь слыхала крик мой «мама»,<br/>
            чему-то, что пищало, скача на ветке.<br/>
            Еще смеялись, что отец был с бантом.<br/>
            И, устыженная, я просыпалась.
        </p>
        <p>
            Но вот однажды<br/>
            в ночь на обычную субботу<br/>
            с обычной пятницы<br/>
            они пришли такими, каких ждала.<br/>
            Приснились, но из сна как бы изъяты,<br/>
            сами собой и сами по себе.<br/>
            Внутри видения померкли прочие возможности,<br/>
            случайного не завершался облик.<br/>
            И лишь они, прекрасные, яснели.<br/>
            И снились долго. Долго и счастливо.
        </p>
        <p>
            Я пробудилась. Я глаза открыла.<br/>
            Коснулась мира, как рельефной рамы.
        </p>
