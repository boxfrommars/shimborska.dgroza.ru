        <h3>Pamięć nareszcie</h3>
        <p>
            Pamięć nareszcie ma, czego szukała.<br/>
            Znalazła mi się matka, ujrzał mi się ojciec.<br/>
            Wyśniłam dla nich stół, dwa krzesła. Siedli.<br/>
            Byli mi znowu swoi i znowu mi żyli.<br/>
            Dwoma lampami twarzy o szarej godzinie<br/>
            błyśli jak Rembrandtowi.
        </p>
        <p>
            Teraz dopiero mogę opowiedzieć,<br/>
            w ilu snach się tułali, w ilu zbiegowiskach<br/>
            spod kół ich wyciągałam,<br/>
            w ilu agoniach przez ile mi lecieli rąk.<br/>
            Odcięci — odrastali krzywo.<br/>
            Niedorzeczność zmuszała ich do maskarady.<br/>
            Cóż stąd, że to nie mogło ich poza mną boleć,<br/>
            jeśli bolało ich we mnie.<br/>
            Śniona gawiedź słyszała, jak wołałam mamo<br/>
            do czegoś, co skakało piszcząc na gałęzi.<br/>
            I był śmiech, że mam ojca z kokardą na głowie.<br/>
            Budziłam się ze wstydem.
        </p>
        <p>
            No i nareszcie.<br/>
            Pewnej zwykłej nocy,<br/>
            z pospolitego piątku na sobotę,<br/>
            tacy mi nagle przyszli, jakich chciałam.<br/>
            Śnili się, ale jakby ze snów wyzwoleni,<br/>
            posłuszni tylko sobie i niczemu już.<br/>
            W głębi obrazu zgasły wszystkie możliwości.<br/>
            przypadkom brakło koniecznego kształtu.<br/>
            Tylko oni jaśnieli piękni, bo podobni.<br/>
            Zdawali mi się długo, długo i szczęśliwie.
        </p>
        <p>
            Zbudziłam się. Otwarłam oczy.<br/>
            Dotknęłam świata jak rzeźbionej ramy.
        </p>
