    <div class="poem" lang="pl">
        <h3>Szkielet jaszczura</h3>
        <p>
            Kochani Bracia,<br/>
            widzimy tutaj przykład złych proporcji:<br/>
            oto szkielet jaszczura piętrzy się przed nami&nbsp;–
        </p>
        <p>
            Drodzy Przyjaciele,<br/>
            na lewo ogon w jedną nieskończoność,<br/>
            na prawo szyja w drugą&nbsp;–
        </p>
        <p>
            Szanowni Towarzysze,<br/>
            pośrodku cztery łapy, co ugrzęzły w mule<br/>
            pod pagórem tułowia&nbsp;–
        </p>
        <p>
            Łaskawi Obywatele,<br/>
            przyroda się nie myli, ale lubi żarty:<br/>
            proszę zwrócić uwagę na tę śmieszną główkę&nbsp;–
        </p>
        <p>
            Panie, Panowie,<br/>
            taka główka niczego nie mogła przewidzieć<br/>
            i dlatego jest główką wymarłego gada&nbsp;–
        </p>
        <p>
            Czcigodni Zgromadzeni,<br/>
            za mało mózgu, za duży apetyt,<br/>
            więcej głupiego snu niż mądrej trwogi&nbsp;–
        </p>
        <p>
            Dostojni Goście,<br/>
            pod tym względem jesteśmy w dużo lepszej formie,<br/>
            życie jest piękne i ziemia jest nasza&nbsp;–
        </p>
        <p>
            Wyborni Delegaci,<br/>
            niebo gwiaździste nad myślącą trzciną,<br/>
            prawo moralne w niej&nbsp;–
        </p>
        <p>
            Prześwietna Komisjo,<br/>
            udało się raz<br/>
            i może tylko pod tym jednym słońcem&nbsp;–
        </p>
        <p>
            Naczelna Rado,<br/>
            jakie zręczne ręce,<br/>
            jakie wymowne usta,<br/>
            ile głowy na karku&nbsp;–
        </p>
        <p>
            Najwyższa Instancjo,<br/>
            cóż za odpowiedzialność na miejsce ogona&nbsp;–
        </p>
    </div>
