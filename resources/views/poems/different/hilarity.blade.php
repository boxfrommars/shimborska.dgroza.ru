    <div class="poem" lang="pl">
        <h3>Sto pociech</h3>
        <p>
            Zachciało mu się szczęścia,<br/>
            zachciało mu się prawdy,<br/>
            zachciało mu się wieczności,<br/>
            patrzcie go!
        </p>
        <p>
            Ledwie rozróżnił sen od jawy,<br/>
            ledwie domyślił się, że on to on,<br/>
            ledwie wystrugał ręką z płetwy rodem<br/>
            krzesiwo i rakietę,<br/>
            łatwy do utopienia w łyżce oceanu,<br/>
            za mało nawet śmieszny, żeby pustkę śmieszyć,<br/>
            oczami tylko widzi,<br/>
            uszami tylko słyszy,<br/>
            rekordem jego mowy jest tryb warunkowy,<br/>
            rozumem gani rozum,<br/>
            słowem: prawie nikt,<br/>
            ale wolność mu w głowie, wszechwiedza i byt<br/>
            poza niemądrym mięsem.<br/>
            Patrzcie go!
        </p>
        <p>
            Bo przecież chyba jest,<br/>
            naprawdę się wydarzył<br/>
            pod jedną z gwiazd prowincjonalnych.<br/>
            Na swój sposób żywotny i wcale ruchliwy,<br/>
            Jak na marnego wyrodka kryształu&nbsp;–<br/>
            dość poważnie zdziwiony.<br/>
            Jak na trudne dzieciństwo w koniecznościach stada&nbsp;–<br/>
            nieźle już poszczególny.<br/>
            Patrzcie go!
        </p>
        <p>
            Tylko tak dalej, dalej choć przez chwilę,<br/>
            bodaj przez mgnienie galaktyki małej!<br/>
            Niechby się wreszcie z grubsza okazało,<br/>
            czym będzie, skoro jest.<br/>
            A jest&nbsp;– zawzięty.<br/>
            Zawzięty, trzeba przyznać, bardzo.<br/>
            Z tym kółkiem w nosie, w tej todze, w tym swetrze.<br/>
            Sto pociech, bądź co bądź.<br/>
            Niebożę.<br/>
            Istny człowiek.
        </p>
